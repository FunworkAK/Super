const FONDOS = ['#F6D7B0', '#CFE8D5', '#F4C7C3', '#D9E4F5', '#F7E3A1', '#E5D4F0', '#D3EFEA', '#FBD9C4'];

export function fondoReceta(id: string): string {
  let h = 0;
  for (const c of id) h = (h * 31 + c.charCodeAt(0)) | 0;
  return FONDOS[Math.abs(h) % FONDOS.length];
}

